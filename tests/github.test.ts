import { test } from "node:test";
import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { authFixture, cookies } from "./fixtures/auth";

test("GitHub OAuth linking protects state, encrypts credentials and isolates repository access", async context => {
  process.env.GITHUB_CLIENT_ID = "fixture-client"; process.env.GITHUB_CLIENT_SECRET = "fixture-secret";
  const originalFetch = globalThis.fetch;
  const { auth, database: pool, base, call } = await authFixture(context, 'github', () => { globalThis.fetch = originalFetch; });
  const email = randomUUID() + "@example.test";
  const signup = await call("sign-up/email", { name: "GitHub fixture", email, password: "Abcd1234" });
  assert.equal(signup.status, 200);
  const user = (await signup.json()).user, cookie = cookies(signup);
  await pool.query('UPDATE "user" SET "emailVerified"=true WHERE id=$1', [user.id]);
  const headers = new Headers({ Cookie: cookie, Origin: base });
  const github = await import("../app/api/account/github/route");
  const readStatus = (sessionCookie = cookie) => github.GET(new Request(base + "/api/account/github", { headers: { Cookie: sessionCookie } }));
  assert.equal((await readStatus("")).status, 401);
  assert.equal((await github.DELETE(new Request(base + "/api/account/github", { method: "DELETE", headers: { Cookie: cookie, Origin: "https://other.example" } }))).status, 403);
  const before = await readStatus();
  assert.equal(before.headers.get("Cache-Control"), "no-store");
  assert.deepEqual(await before.json(), { configured: true, connected: false, repositoryScope: false, callbackURL: base + "/api/auth/callback/github" });
  const { repositoryToken } = await import("../lib/github");
  const form = new FormData(); form.set("useConnectedGitHub", "true");
  const request = new Request(base, { headers });
  await assert.rejects(() => repositoryToken(request, form), /Connect GitHub/);
  delete process.env.GITHUB_CLIENT_SECRET;
  assert.equal((await (await readStatus()).json()).configured, false);
  await assert.rejects(() => repositoryToken(request, form), /not configured/);
  process.env.GITHUB_CLIENT_SECRET = "fixture-secret";
  assert.equal((await call("link-social", { provider: "github" })).status, 401);

  let profileEmail = email;
  const token = "gho_fixture_token", sha = "a".repeat(40);
  const requests: { url: string; authorization: string | null }[] = [];
  globalThis.fetch = async (input, init) => {
    const url = input instanceof Request ? input.url : String(input);
    const authorization = new Headers(init?.headers || (input instanceof Request ? input.headers : undefined)).get("Authorization");
    requests.push({ url, authorization });
    if (url === "https://github.com/login/oauth/access_token") return Response.json({ access_token: token, token_type: "bearer", scope: "read:user,user:email,repo" });
    if (url === "https://api.github.com/user") return Response.json({ id: 12345, login: "fixture", name: "Fixture", email: profileEmail });
    if (url === "https://api.github.com/user/emails") return Response.json([{ email: profileEmail, primary: true, verified: true }]);
    if (url.includes("/commits/")) return Response.json({ sha });
    if (url.includes("/zipball/")) return new Response(null, { status: 302, headers: { Location: "https://codeload.github.com/fixture/private/zip/" + sha + "?temporary=fixture" } });
    if (url.startsWith("https://codeload.github.com/")) return new Response(new Uint8Array([1, 2, 3]));
    throw new Error("Unexpected fixture request: " + url);
  };
  async function begin() {
    const response = await call("link-social", { provider: "github", scopes: ["repo"], callbackURL: "/account", errorCallbackURL: "/account?github=error", disableRedirect: true }, cookie);
    assert.equal(response.status, 200);
    const url = new URL((await response.json()).url);
    assert.equal(url.origin, "https://github.com");
    assert.equal(url.searchParams.get("redirect_uri"), base + "/api/auth/callback/github");
    assert.ok(url.searchParams.get("scope")?.split(" ").includes("repo"));
    return { state: url.searchParams.get("state")!, cookie: cookie + "; " + cookies(response) };
  }
  const invalid = await begin();
  await auth.handler(new Request(base + "/api/auth/callback/github?code=fixture&state=tampered", { headers: { Cookie: invalid.cookie } }));
  assert.equal((await (await readStatus()).json()).connected, false);
  profileEmail = "different@example.test";
  const mismatch = await begin();
  await auth.handler(new Request(base + "/api/auth/callback/github?code=fixture&state=" + encodeURIComponent(mismatch.state), { headers: { Cookie: mismatch.cookie } }));
  assert.equal((await (await readStatus()).json()).connected, false, "A different email cannot be linked");
  profileEmail = email;
  const valid = await begin();
  const callback = await auth.handler(new Request(base + "/api/auth/callback/github?code=fixture&state=" + encodeURIComponent(valid.state), { headers: { Cookie: valid.cookie } }));
  assert.equal(callback.status, 302);
  assert.equal(new URL(callback.headers.get("Location")!, base).pathname, "/account");
  const saved = (await pool.query('SELECT id,"accessToken" FROM account WHERE "userId"=$1 AND "providerId"=\'github\'', [user.id])).rows[0];
  assert.ok(saved); assert.notEqual(saved.accessToken, token); assert.ok(!saved.accessToken.includes(token));
  const status = await (await readStatus()).json();
  assert.equal(status.connected, true); assert.equal(status.repositoryScope, true);
  assert.ok(!JSON.stringify(status).includes(token)); assert.ok(!JSON.stringify(status).includes("fixture-secret"));
  assert.equal(await repositoryToken(request, form), token);
  const { githubArchive } = await import("../lib/python-tools");
  const snapshot = await githubArchive("https://github.com/fixture/private", "feature/example", await repositoryToken(request, form));
  assert.equal(snapshot.source, "https://github.com/fixture/private/tree/" + sha);
  assert.ok(!JSON.stringify(snapshot).includes(token));
  assert.ok(requests.find(call => call.url.includes("/commits/"))?.url.endsWith("feature%2Fexample"));
  assert.equal(requests.find(call => call.url.includes("/commits/"))?.authorization, "Bearer " + token);
  assert.equal(requests.find(call => call.url.includes("/zipball/"))?.authorization, "Bearer " + token);
  assert.equal(requests.find(call => call.url.startsWith("https://codeload.github.com/"))?.authorization, null);
  globalThis.fetch = async input => String(input).includes("/commits/") ? Response.json({ sha }) : new Response(null, { status: 302, headers: { Location: "https://untrusted.example/archive" } });
  await assert.rejects(githubArchive("https://github.com/fixture/private", "main", token), /authorize/);
  globalThis.fetch = originalFetch;
  for (const path of ["get-access-token", "refresh-token"]) assert.equal((await call(path, { accountId: saved.id }, cookie)).status, 404, "HTTP token endpoints must be disabled");
  const listed = await auth.handler(new Request(base + "/api/auth/list-accounts", { headers }));
  assert.ok(!(await listed.text()).includes(token));
  const other = await call("sign-up/email", { name: "Other user", email: randomUUID() + "@example.test", password: "Abcd1234" });
  const otherCookie = cookies(other);
  assert.equal((await (await readStatus(otherCookie)).json()).connected, false);
  await assert.rejects(() => auth.api.getAccessToken({ headers: new Headers({ Cookie: otherCookie }), body: { accountId: saved.id } }));
  form.set("githubToken", "manual_fixture");
  await assert.rejects(() => repositoryToken(request, form), /not both/);
  form.delete("useConnectedGitHub"); assert.equal(await repositoryToken(request, form), "manual_fixture");
  const unlink = await github.DELETE(new Request(base + "/api/account/github", { method: "DELETE", headers }));
  assert.equal(unlink.status, 200);
  assert.equal((await (await readStatus()).json()).connected, false);
  assert.equal((await pool.query('SELECT count(*) FROM account WHERE "providerId"=\'github\' AND "userId"=$1', [user.id])).rows[0].count, "0");
  assert.equal((await call("sign-in/email", { email, password: "Abcd1234" })).status, 200, "Disconnecting must preserve password sign-in");
});
